// 【凶手】轮机长 阮仲平。
// 【动机】2016 年，船主祁望川的旧游艇“海鸥号”在锚地发动机舱起火，二十二岁的甲板水手阮小海（阮仲平独子）死亡。
//   真因：祁为省钱，把燃油软管的更换期一拖再拖。事后官方报告写成“值班水手醉酒睡岗、碰翻油桶”，时任船长江启明在祁的授意下签了字。
//   阮仲平背了八年“儿子醉酒害死自己”的名声，这回受邀上船，是祁念旧、要“照顾老人”。
//   生日宴的祝酒词里，祁喝多了，笑着对阮、江二人说：“当年海鸥号那件事，要不是我出面把报告压成那样，你们俩哪有今天！”阮这才知道儿子是被推出去顶罪的。
// 【手法：没有人走进过那间上了闩的屋子】
//   祁的主人套房在尾部下层，与发电机舱仅隔一道舱壁，共用一条通风格栅。夜里发电机固定 22:30–06:30 运转供空调（值班日志有记载）。
//   1) 22:05 阮借口“看机器”下发电机舱，把湿排气软管的卡箍松开三圈，排气漏进舱内，顺通风格栅渗进主卧衣帽间。
//   2) 22:20 阮以“月度检修”名义（他本职）进主卧，拆走一氧化碳报警器的 9 伏电池（带“B-07”标签）。电池后来在他的头灯里。
//   3) 22:40 祁回舱前，阮当着卓小满说：“后半夜有雷阵雨，舷窗关严点，别让雨飘进去。”祁一向睡觉要开着一指宽的舷窗（嫌闷），
//      22:50 卓送威士忌时，亲眼看见祁在拧死舷窗，嘟囔“老阮说后半夜有雨”。22:58 许文彬敲门，祁隔门喊“雨要来了，窗我都关了，明早再说”，并闩上门闩。
