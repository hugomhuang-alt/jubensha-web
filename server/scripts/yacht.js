//   许文彬：22:58 在门外与祁争执股权合同；伪造过一份签字。
//   甘老五：偷酒喝，22:10 躲在后甲板储物柜里，亲眼见阮从发电机舱出来，满手油污；起初不敢说。
//   戚野：23:40 与听雪在艉部，听见落水声；01:10 拍星空。
// 【解题链】一氧化碳(尸斑/发电机运转日志) -> 人为(卡箍划痕+报警器无电池) -> 谁让他关窗(卓的证词+许听到的话) -> 天气实为晴(气象记录/星空照/毛巾) -> 说谎的是阮 -> 头灯里的 B-07 电池 + 甘老五目击 + 海鸥号旧案动机。
