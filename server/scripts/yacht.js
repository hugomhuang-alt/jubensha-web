//   4) 祁服了安眠药（每晚一粒，白砚秋开的），睡着后吸入一氧化碳死亡，约在 00:30 前后。门从里面闩着——因为从头到尾就没有人进去过。
// 【表面真相与反转】
//   第一层：现场像“密室”，船医验出一氧化碳中毒、樱桃红尸斑 -> “老发电机漏气，意外”；矛头指向签了“已检查”的船长江启明（疏忽，或故意）。
//   第二层：发电机舱卡箍有新鲜工具划痕，报警器被拿走电池 -> 不是意外，是人为。
//   第三层：谁能让一个习惯开窗的老人自己把窗关死？只有说“有雨”的人。气象记录晴 -> 阮撒了谎。电池在阮头灯里 -> 铁证。
// 【红鲱鱼】
//   江启明：在海鸥号报告上签字（有杀人理由：祁要在这次航程后辞退他并翻旧账）；“已检查”其实没下去检查（打了个盹）。
