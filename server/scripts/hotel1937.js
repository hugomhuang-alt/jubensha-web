// ============================ 作者解题笔记（不展示给玩家）============================
// 【背景】1937 年 11 月 11 日夜，淞沪战事末期，次日国军撤出南市，租界即将成为“孤岛”。公共租界边缘的沪安饭店（虚构）五楼 506 套房，
//   绸业巨子、救济会会长容世铭（63，左撇子）在为他送行的“惜别宴”之夜死亡。他原定次晨六点乘船赴港。
// 【真相】凶手 = 掌柜 柴敬斋。动机：他为了给十八户饭店伙计家属换来租界外的通行证，一年来把沪安客簿（军官住宿情况）誊抄后卖给一个“张先生”。
//   容世铭从记者程子衡手里拿到那份抄本，认出是账房笔迹，下午 17:00 当面对柴说：“明早我把它交给岑少校。你是自己去说，还是我替你说。”
// 【手法】毒不在酒里，在冰里。容有个老规矩：夜里只喝一杯威士忌，只放一整块敲下来的大冰，慢慢化着喝，冰要掌柜亲手敲、亲手送。
//   柴 15:20 从地下镀银间铁橱里取走氰化钾；19:40 在冰箱里用烧红的铁钉在大冰块中心烫出小孔，填进毒粉，浇水冻回；22:15 以“老规矩”亲取，
//   用铜碗盛着、毛巾裹着，交阿旺送上 506（22:20）。容 22:58 把冰放进杯子，倒酒慢慢喝；外层冰化到毒核露出，约 23:20 起毒发，23:26 倒下。
//   延迟致死使“最后接触者”（冯、夫人、记者）都成了嫌疑，而真正下手的时间是 19:40。
// 【伪装（表面真相）】23:35 柴用总钥匙开门，借阿旺下楼叫人的两三分钟，把厨房取来的砒霜（鼠药）撒进酒瓶，又往杯里倒了点酒搅了搅，扶正酒杯。
//   于是酒瓶、杯中都验出砒霜；舞女白露领过鼠药、当晚在场、瓶身有她的朱红指痕、她还撒谎说没上过楼——“凶手是白露，毒在酒里”看似铁证。
// 【真实时间线】
//   15:20 柴取氰化钾（镀银间称重少 18 克）。17:00 容当面摊牌。19:40 柴做毒冰。21:00 惜别宴。21:50 程子衡经阿旺开门进 506 偷拍桌上文件（此时桌上无杯无碗）。
//   21:30 白露在舞池当众骂容“不得好死”（容扣着她的卖身契）。22:15 柴取冰；22:20 阿旺送碗。22:40–22:50 岑少校取走十二根金条，容左手签收据（22:45）；岑走后门楼梯。
//   22:56–23:04 白露上楼，容签了她的解约书（22:58），把大冰放进杯里，给白露与自己各倒一杯；白露喝的是纯酒，什么事也没有。
//   23:05–23:12 冯仲谦为催债争吵。23:13–23:19 沈夫人送心脏药水，见他脸红出汗。23:21 容拨前台，只有喘息，柴吩咐“醉了，不管”。
//   23:26 隔壁 507 的乔医生听见椅子倒地声。23:28 程子衡敲门无应。23:35 柴开门；23:36–23:38 柴独自在屋内动酒瓶。23:38 乔进屋，看见柴扶杯、晃瓶。
// 【解题链（needs 四层）】
//   一层：死因与时间——樱红面色、苦杏仁味、半小时内倒毙＝氰化物，而酒瓶里验出的是砒霜（砒霜不会这么快）。→ 瓶中的毒不是死因。
//   二层：杯中残液验出氰化物，瓶中没有；白露自己喝过同一瓶酒平安无事（阿旺、她的解约书佐证）。→ 氰化物是通过“只进杯子、不进瓶子”的东西进去的。
//   三层：杯底水圈已干、圈上压着一滴未干的酒渍＝酒是死后补倒的（谁补？开门后独处的柴，乔的笔记）；
//         同时铜碗里留着干透的结晶、容的“一整块大冰”老规矩、取冰簿“掌柜自取”、冰箱里的试验冰孔（烫孔填毒）→ 毒是冰带进去的。
//   四层：谁能做毒冰？镀银间氰化钾少 18 克，钥匙只有柴一把；试验冰里的铁钉；总机日志他无视 23:21 的呼救；客簿抄本用的是柴记账房红格笺——动机。
// 【红鲱鱼】白露（鼠药、指痕、撒谎、当众咒骂）；冯仲谦（懂电镀、懂氰化物、23:05 吵架、雪茄烟蒂、撒谎在牌室）；
//   沈夫人（最后一个送药、遗嘱被删、撒谎没出过房）；程子衡（偷拍、行贿阿旺、23:28 敲门）；乔维岳（吗啡成瘾、药箱少三支）；阿旺（送碗人、放人进房）；岑克明（金条、撒谎）。
